// 影トークンの単一定義箇所（Requirement 1.1）。
// 影色は 8 桁 hex（末尾 2 桁がアルファ）で表現し、rgba() 関数値を避けて hex リテラル方針を保つ。
//
// 意匠の出典（docs/design/upstream/airbnb-DESIGN.md）は **影を 1 段しか持たない**。
// 面の分離は影ではなく 1px の輪郭と余白が担い、深さは写真と角丸のクリッピングで表現する、
// という設計思想による。本プロジェクトもこれに倣い 1 段だけを提供する。
//
// 撤去前の 3 段（sm / md / lg）は ts/apps と ts/packages/ui/src のどこからも使われておらず
// （出現は theme.css の宣言 3 行のみ）、Tailwind は未参照のテーマ変数を出力しないため、
// 撤去時点で描画には現れていなかった。したがって画面への影響は無い。
//
// 名前を無印にしない理由: 無印は Tailwind 既定のユーティリティ名と同名になり、
// 上書きすると既定クラスの意味が静かに変わる。名前付きの段は加算的で曖昧さがない。

