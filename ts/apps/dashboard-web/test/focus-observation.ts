// 焦点の観測点を確定させるための共有ヘルパー（Issue #166）。
//
// `findBy*` / `waitFor` は条件が満たされた直後に **1 マクロタスクだけ**待って戻る
// （RTL の asyncWrapper が act 環境を切り、`setTimeout(resolve, 0)` で排出する）。
// 一方 React の passive effect（`useEffect`）は Scheduler 経由で流れ、これもマクロタスクである。
// 両者の順序は保証されておらず、CI の負荷が高いと入れ替わる。その瞬間に焦点を観測すると:
//
//   - 「焦点が **移る** こと」を見る比較は **偽の赤** になる
//     （2026-08-30 に実発生。同一コミットの再実行で緑・run 33265933448）
//   - 「焦点を **奪わない** こと」を見る比較は **偽の緑** になる
//     （実測: 横取りを注入しただけなら検出できるが、その横取りを 1 マクロタスク遅らせた
//      組合せでは 1 件も赤にならなかった。観測点が横取りより前に来るため）
//
// 前者は `await waitFor(() => expect(document.activeElement).toBe(...))` で収束を待てば足りる。
// **後者に waitFor を使ってはならない** — 条件は最初から成立しているので即座に通り、
// 検査を弱めるだけになる。否定側は待つのではなく **観測点そのものを確定させる**必要がある。
//
// act は React の作業ループを同期的に流し切るので、抜けた時点で保留中の passive effect は無い。
// 「焦点を奪わないこと」を見る比較の直前に置くこと。
import { act } from '@testing-library/react';

export async function settleEffects(): Promise<void> {
  // act の中でマクロタスクを 1 回跨ぐ。act だけでは **React の作業ループしか流れない**ため、
  // マクロタスク越しに起きる焦点操作を観測点の後ろへ取りこぼす（実測: act だけの版では
  // 上記の「遅らせた横取り」を 1 件も検出できなかった）。跨いだうえで act を抜ければ、
  // その間に発生した再描画と effect も流れ切っている。
  //
  // **これは「一定時間待つ」ではない。** 跨ぐのは 1 マクロタスクちょうどで、その後の比較は
  // 完全一致である。長いタイマー越しの横取りまでは捕まえられないが、本コンポーネントは
  // タイマーを持たない（焦点操作は passive effect 内で同期に行う）。
  await act(async () => {
    await new Promise<void>((resolve) => setTimeout(resolve, 0));
  });
}
